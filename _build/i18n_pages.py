def _norm(t):
    return " ".join(html.unescape(t).split())


def tr_html(src, lang):
    """Translate the visible text and labels of an English HTML fragment."""
    D = {_norm(k): v for k, v in L10N[lang]["ui"].items()}
    for a, b in L10N[lang]["frag"]:
        src = src.replace(a, b)

    def text(m):
        raw = m.group(1); k = _norm(raw)
        if k not in D:
            return m.group(0)
        lead = raw[:len(raw) - len(raw.lstrip())]; trail = raw[len(raw.rstrip()):]
        return ">" + lead + D[k] + trail + "<"
    src = _re.sub(r">([^<]+)<", text, src)

    def attr(m):
        k = _norm(m.group(2))
        return f'{m.group(1)}="{html.escape(_re.sub("<[^>]+>", "", D[k]))}"' if k in D else m.group(0)
    return _re.sub(r'\b(placeholder|aria-label|title|alt)="([^"]*)"', attr, src)


def leftovers(page, where):
    """Warn about English words left in visible text, so nothing slips through untranslated."""
    body = _re.sub(r"<script.*?</script>|<style.*?</style>|<svg.*?</svg>|<code.*?</code>", " ", page, flags=_re.S)
    found = set()
    for m in _re.finditer(r">([^<]+)<", body):
        for w in [x for x in _re.findall(r"[^\W\d_]+(?:'[^\W\d_]+)?", html.unescape(m.group(1))) if x.isascii()]:
            if LANG == "ar" and w not in I18N_ALLOW and not w.isupper() and w not in ("e", "tool", "box", "co", "uk", "hello"):
                found.add(w)
            elif LANG != "ar" and w.lower() in EN_WORDS and w not in ("tool",):
                found.add(w)
    if found:
        print(f"  ! {where}: possible English left: {' '.join(sorted(found)[:30])}")


def i18n_js(lang):
    loc = L10N[lang]
    tools = {s: [loc["pages"][s]["name"], loc["pages"][s]["desc"], lpath(s, lang)] for s in loc["slugs"]}
    data = {"lang": lang, "s": {**{_norm(k): v.strip() for k, v in loc["ui"].items()}, **{k: v for k, v in loc["ui"].items() if k != _norm(k)}}, "tools": tools}
    with open(os.path.join(OUT, "assets", f"i18n-{lang}.js"), "w") as f:
        f.write("/* etoolbox " + loc["name"] + " strings (generated by _build/i18n_pages.py) */\nwindow.ETB_I18N=" + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")


def l_card(slug, lang):
    p = L10N[lang]["pages"][slug]
    return f'<a class="tool-card" href="{lpath(slug, lang)}">{tool_icon(slug)}<h3>{p["name"]}</h3><p>{p["desc"]}</p></a>'


def l_share(path, text, c):
    from urllib.parse import quote
    u = quote(SITE + path, safe=""); t = quote(text, safe="")
    links = [("WhatsApp", f"https://wa.me/?text={t}%20{u}", "message-circle"), ("X", f"https://x.com/intent/post?text={t}&url={u}", None),
             ("LinkedIn", f"https://www.linkedin.com/sharing/share-offsite/?url={u}", None), ("Facebook", f"https://www.facebook.com/sharer/sharer.php?u={u}", None),
             (c["email"], f"mailto:?subject={t}&body={u}", "mail")]
    a = "".join(f'<a class="sh" href="{h}" target="_blank" rel="noopener nofollow" data-net="{n}">{svg(i) if i else ""}{n}</a>' for n, h, i in links)
    return (f'<div class="share-bar" data-url="{SITE}{path}" data-text="{html.escape(text)}"><span class="sh-lead">{svg("share-2")} {c["share_lead"]}</span>'
            f'<button type="button" class="sh sh-native" hidden>{svg("share-2")}{c["share"]}</button>{a}'
            f'<button type="button" class="sh sh-copy">{svg("link")}<span>{c["copy"]}</span></button></div>')


def l_faq(faqs, c):
    items = "".join(f"<details><summary>{q}</summary><p>{a}</p></details>" for q, a in faqs)
    return f'<section class="faq prose"><h2>{c["faq"]}</h2>{items}</section>'


def l_tool_page(slug, lang):
    loc = L10N[lang]; c = loc["chrome"]; p = loc["pages"][slug]; src = TOOL_SRC[slug]
    path = lpath(slug, lang)
    cat = next(k for k, ss in I18N_CATS if slug in ss)
    bl = {"@context": "https://schema.org", "@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": 1, "name": c["home"], "item": SITE + loc["home"]},
        {"@type": "ListItem", "position": 2, "name": loc["cats"][cat][0], "item": SITE + loc["home"] + "#" + cat},
        {"@type": "ListItem", "position": 3, "name": html.unescape(p["h1"]), "item": SITE + path}]}
    app = {"@context": "https://schema.org", "@type": "WebApplication", "name": html.unescape(p["h1"]), "url": SITE + path, "inLanguage": loc["html"],
           "applicationCategory": "BusinessApplication", "operatingSystem": "Any", "offers": {"@type": "Offer", "price": "0", "priceCurrency": "GBP"}}
    ld = faq_ld(p["faqs"]) + f'<script type="application/ld+json">{json.dumps(app, ensure_ascii=False)}</script>\n<script type="application/ld+json">{json.dumps(bl, ensure_ascii=False)}</script>\n'
    others = [s for s in loc["slugs"] if s != slug]
    others.sort(key=lambda s: (s not in dict(I18N_CATS)[cat], list(loc["slugs"]).index(s)))
    page = head(p["title"], p["intro"], path, ld + src["extra"]) + f"""
<div class="wrap">
  <nav class="crumbs" aria-label="{c["crumbs"]}"><a href="{loc["home"]}">{c["home"]}</a><span aria-hidden="true">›</span><a href="{loc["home"]}#{cat}">{loc["cats"][cat][0]}</a><span aria-hidden="true">›</span><span aria-current="page">{p["name"]}</span></nav>
  <div class="page-head" data-slug="{slug}"><div class="ph-row">{tool_icon(slug)}<h1>{p["h1"]}<button type="button" class="fav-btn" aria-pressed="false">{c["fav"]}</button></h1></div><p>{p["intro"]}</p><span class="privacy-tag">{svg("lock")} {c["tag"]}</span></div>
  {tr_html(src["ui"], lang)}
  {l_share(path, html.unescape(p["h1"]) + c["share_suffix"], c)}
  <section class="prose">{p["body"]}</section>
  {l_faq(p["faqs"], c)}
  <section><h2>{c["more"]}</h2><div class="grid">{"".join(l_card(s, lang) for s in others[:8])}</div></section>
</div>
""" + foot(src["scripts"])
    leftovers(page[page.index("<main"):], path)
    write(path, page)


